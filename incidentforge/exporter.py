class MarkdownExporter:
    """Export incidents as individual Markdown files."""

    def __init__(self, output_dir: Path):
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)

    async def export(self, incident: Incident) -> Path:
        """
        Export incident as Markdown file.

        Args:
            incident: Incident to export.

        Returns:
            Path to created file.
        """
        content = self._render_markdown(incident)
        file_path = self.output_dir / f"{incident.id}.md"

        async with aiofiles.open(file_path, "w", encoding="utf-8") as f:
            await f.write(content)

        return file_path

    def _render_markdown(self, incident: Incident) -> str:
        """Render incident as Markdown."""
        lines = [
            f"# {incident.id}",
            "",
            f"**Service:** {incident.service}",
            f"**Severity:** {incident.severity.value}",
            f"**Duration:** {incident.outage_duration_minutes} minutes",
            f"**Failure Category:** {incident.failure_category.value}",
            f"**Generated:** {incident.metadata.generated_at}",
            f"**Model:** {incident.metadata.model}",
            f"**Prompt Version:** {incident.metadata.prompt_version}",
            f"**Seed:** {incident.metadata.seed}",
            "",
            "## SLA Impact",
            "",
            f"- **Availability Before:** {incident.sla_impact.availability_before:.4f}",
            f"- **Availability After:** {incident.sla_impact.availability_after:.4f}",
            f"- **P99 Latency:** {incident.sla_impact.p99_latency_ms} ms",
            "",
            "## Root Cause Analysis",
            "",
            incident.root_cause_analysis,
            "",
            "## Timeline",
            "",
        ]

        for event in incident.timeline:
            severity_str = f" [{event.severity.value}]" if event.severity else ""
            lines.append(f"- **{event.timestamp}** ({event.source}){severity_str}: {event.event}")

        lines.extend([
            "",
            "## Action Items",
            "",
        ])

        for item in incident.action_items:
            lines.append(f"- **[{item.priority}]** {item.action} — *Owner: {item.owner}*")

        lines.extend([
            "",
            "---",
            "",
            f"*This incident is synthetic (generated by IncidentForge v{incident.metadata.schema_version}).*",
            f"*Do not use as factual reference for real incidents.*",
        ])

        return "\n".join(lines)

    async def export_batch(self, incidents: list[Incident]) -> list[Path]:
        """Export multiple incidents."""
        tasks = [self.export(incident) for incident in incidents]
        return await asyncio.gather(*tasks)


class JSONLExporter:
    """Export incidents as JSONL (one JSON per line)."""

    def __init__(self, output_path: Path):
        self.output_path = output_path
        self.output_path.parent.mkdir(parents=True, exist_ok=True)
        self._file_handle: Any = None

    async def __aenter__(self):
        self._file_handle = await aiofiles.open(self.output_path, "w", encoding="utf-8")
        return self

    async def __aexit__(self, exc_type, exc_val, exc_tb):
        if self._file_handle:
            await self._file_handle.close()

    async def export(self, incident: Incident) -> None:
        """Export single incident as JSONL line."""
        if self._file_handle is None:
            raise RuntimeError("Exporter not opened. Use async context manager.")

        line = incident.model_dump_json(exclude_none=True)
        await self._file_handle.write(line + "\n")

    async def export_batch(self, incidents: list[Incident]) -> None:
        """Export multiple incidents."""
        for incident in incidents:
            await self.export(incident)

    async def flush(self) -> None:
        """Flush buffer to disk."""
        if self._file_handle:
            await self._file_handle.flush()


class ParquetExporter:
    """Export incidents as Parquet file."""

    def __init__(self, output_path: Path):
        self.output_path = output_path
        self.output_path.parent.mkdir(parents=True, exist_ok=True)
        self._buffer: list[dict] = []

    def _flatten_incident(self, incident: Incident) -> dict:
        """Flatten incident for tabular storage."""
        base = {
            "id": incident.id,
            "service": incident.service,
            "severity": incident.severity.value,
            "outage_duration_minutes": incident.outage_duration_minutes,
            "failure_category": incident.failure_category.value,
            "availability_before": incident.sla_impact.availability_before,
            "availability_after": incident.sla_impact.availability_after,
            "p99_latency_ms": incident.sla_impact.p99_latency_ms,
            "root_cause_analysis": incident.root_cause_analysis,
            "timeline_events": len(incident.timeline),
            "action_items_count": len(incident.action_items),
            "model": incident.metadata.model,
            "prompt_version": incident.metadata.prompt_version,
            "seed": incident.metadata.seed,
            "generated_at": incident.metadata.generated_at,
            "schema_version": incident.metadata.schema_version,
            "synthetic": incident.metadata.synthetic,
        }

        # Add timeline as JSON string
        base["timeline"] = json.dumps([
            {
                "timestamp": e.timestamp,
                "event": e.event,
                "source": e.source,
                "severity": e.severity.value if e.severity else None,
            }
            for e in incident.timeline
        ], ensure_ascii=False)

        # Add action items as JSON string
        base["action_items"] = json.dumps([
            {
                "action": item.action,
                "owner": item.owner,
                "priority": item.priority.value,
            }
            for item in incident.action_items
        ], ensure_ascii=False)

        return base

    def add(self, incident: Incident) -> None:
        """Add incident to buffer."""
        self._buffer.append(self._flatten_incident(incident))

    def add_batch(self, incidents: list[Incident]) -> None:
        """Add multiple incidents to buffer."""
        for incident in incidents:
            self.add(incident)

    def export(self) -> Path:
        """Write buffer to Parquet file."""
        if not self._buffer:
            raise ValueError("No incidents to export")

        df = pd.DataFrame(self._buffer)
        df.to_parquet(self.output_path, index=False)
        return self.output_path

    async def export_async(self) -> Path:
        """Async export (runs in thread pool)."""
        loop = asyncio.get_event_loop()
        return await loop.run_in_executor(None, self.export)


class ExporterManager:
    """Manages multiple exporters."""

    def __init__(
        self,
        output_dir: Path,
        export_markdown: bool = True,
        export_jsonl: bool = True,
        export_parquet: bool = False,
    ):
        self.output_dir = output_dir
        self.export_markdown = export_markdown
        self.export_jsonl = export_jsonl
        self.export_parquet = export_parquet

        self.markdown_exporter = MarkdownExporter(output_dir / "markdown") if export_markdown else None
        self.jsonl_exporter = JSONLExporter(output_dir / "incidents_dataset.jsonl") if export_jsonl else None
        self.parquet_exporter = ParquetExporter(output_dir / "incidents_dataset.parquet") if export_parquet else None

    async def __aenter__(self):
        if self.jsonl_exporter:
            await self.jsonl_exporter.__aenter__()
        return self

    async def __aexit__(self, exc_type, exc_val, exc_tb):
        if self.jsonl_exporter:
            await self.jsonl_exporter.__aexit__(exc_type, exc_val, exc_tb)

    async def export(self, incident: Incident) -> None:
        """Export incident to all enabled formats."""
        tasks = []

        if self.markdown_exporter:
            tasks.append(self.markdown_exporter.export(incident))

        if self.jsonl_exporter:
            tasks.append(self.jsonl_exporter.export(incident))

        if self.parquet_exporter:
            self.parquet_exporter.add(incident)

        if tasks:
            await asyncio.gather(*tasks)

    async def export_batch(self, incidents: list[Incident]) -> None:
        """Export multiple incidents."""
        for incident in incidents:
            await self.export(incident)

        # Write parquet at the end
        if self.parquet_exporter:
            await self.parquet_exporter.export_async()

    async def finalize(self) -> dict[str, Path]:
        """Finalize exports and return output paths."""
        results = {}

        if self.jsonl_exporter:
            await self.jsonl_exporter.flush()
            results["jsonl"] = self.jsonl_exporter.output_path

        if self.parquet_exporter:
            path = await self.parquet_exporter.export_async()
            results["parquet"] = path

        if self.markdown_exporter:
            results["markdown_dir"] = self.markdown_exporter.output_dir

        return results


async def export_incidents(
    incidents: list[Incident],
    output_dir: Path,
    export_markdown: bool = True,
    export_jsonl: bool = True,
    export_parquet: bool = False,
) -> dict[str, Path]:
    """
    Convenience function to export incidents.

    Args:
        incidents: List of incidents to export.
        output_dir: Output directory.
        export_markdown: Whether to export Markdown files.
        export_jsonl: Whether to export JSONL.
        export_parquet: Whether to export Parquet.

    Returns:
        Dictionary of output paths.
    """
    async with ExporterManager(
        output_dir=output_dir,
        export_markdown=export_markdown,
        export_jsonl=export_jsonl,
        export_parquet=export_parquet,
    ) as manager:
        await manager.export_batch(incidents)
        return await manager.finalize()


